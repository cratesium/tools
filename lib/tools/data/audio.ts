interface PairSpec {
  id: number;
  name: string;
  slug: string;
  from?: string;
  to: "mp3" | "wav";
  fromLabel: string;
  toLabel: string;
  why: string;
  faq: { q: string; a: string };
  keywords: string[];
  seoTitle: string;
  seoDescription: string;
  short: string;
  related: string[];
  popular?: boolean;
}

/** Fixed-target converters (#102–#109) share the Audio Converter component. */
function pair(p: PairSpec): ToolDefinition {
  return aud({
    id: p.id,
    name: p.name,
    slug: p.slug,
    shortDescription: p.short,
    description: `${p.name} converts ${p.fromLabel} audio to ${p.toLabel} directly in your browser. ${p.why} Choose the ${p.to === "wav" ? "bit depth" : "bitrate"}, sample rate and channels, or keep the originals; ${p.to === "mp3" ? "title, artist and album tags and embedded cover art are carried over." : "the result is uncompressed PCM that every editor and DAW can open."}`,
    inputFormats: p.from ? [p.fromLabel] : ANY_AUDIO,
    outputFormats: [p.toLabel],
    processor: "audio.convert",
    processorOptions: p.from ? { to: p.to, from: p.from } : { to: p.to },
    seoTitle: p.seoTitle,
    seoDescription: p.seoDescription,
    instructions: [`Drop your ${p.fromLabel} file.`, p.to === "mp3" ? "Choose a bitrate (192 kbit/s is a good default)." : "Choose 16-bit (CD quality) or 24-bit.", "Optionally change sample rate or convert to mono.", `Click Convert and download the ${p.toLabel} file.`],
    faqs: [p.faq, FORMATS_FAQ, PRIVACY],
    related: p.related,
    keywords: p.keywords,
    popular: p.popular,
  });
}

