/** Shared builder for the fixed-pair converters (#47–#54). */
function pair(
  id: number,
  name: string,
  slug: string,
  from: string,
  to: "png" | "jpeg" | "webp",
  fromLabel: string,
  toLabel: string,
  why: string,
  extra: { faqs: { q: string; a: string }[]; related: string[]; keywords: string[]; seoTitle: string; seoDescription: string; short: string; notes?: string; popular?: boolean },
): ToolDefinition {
  return img({
    id,
    name,
    slug,
    shortDescription: extra.short,
    description: `${name} converts ${fromLabel} images to ${toLabel} directly in your browser – one file or a whole batch at once. ${why} Nothing is uploaded: decoding and encoding happen locally with the Canvas API${from === "heic" ? " and heic2any (libheif in WebAssembly)" : ""}, and you can download each result or everything as a ZIP.${extra.notes ? ` ${extra.notes}` : ""}`,
    inputFormats: [fromLabel],
    outputFormats: [toLabel],
    processor: "image.convert",
    processorOptions: { from, to },
    seoTitle: extra.seoTitle,
    seoDescription: extra.seoDescription,
    instructions: [`Drop one or more ${fromLabel} files.`, to === "png" ? "Conversion is lossless – no quality setting is needed." : `Adjust the quality slider${to === "jpeg" ? " and the background colour for transparent areas" : ""}.`, `Click Convert to ${toLabel}.`, "Download the images individually or as a ZIP."],
    faqs: extra.faqs,
    related: extra.related,
    keywords: extra.keywords,
    popular: extra.popular,
  });
}

